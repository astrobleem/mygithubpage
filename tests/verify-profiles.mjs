import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';
import {validateProfile,windowsConfig,requireLauncher} from '../windows-xt/profiles.mjs';
import {CONFIGS,sha256} from '../windows-xt/core.mjs';
import {bootstrap} from '../windows-xt/diagnostics.mjs';

const root=path.resolve(import.meta.dirname,'..');
createRequire(import.meta.url)(path.join(root,'windows-xt/vendor/emulators.js'));
emulators.pathPrefix=path.join(root,'windows-xt/vendor')+path.sep;
const fixture=new Uint8Array(fs.readFileSync(path.join(root,'tests/FIXTURE.zip')));
const before=await sha256(fixture);
assert.equal(windowsConfig({}),CONFIGS.xt);
assert.equal(fs.readFileSync(path.join(root,'tools/TANDY.CNF'),'utf8').replace(/\r\n/g,'\n'),CONFIGS.xt);
for(const profile of [{machine:'svga_s3'},{machine:'pcjr'},{machine:'pcjr',launcher:'../X.BAT'},{machine:'pcjr',launcher:'PCJR/X%PATH%.BAT'},{machine:'pcjr',launcher:'PCJR/X.BAT & WIN'},{machine:'pcjr',launcher:'C:/X.BAT'}])assert.throws(()=>validateProfile(profile));
const profile=validateProfile({machine:'pcjr',launcher:'pcjr\\startjr.bat'});
assert.deepEqual(profile,{machine:'pcjr',launcher:'PCJR/STARTJR.BAT'});
requireLauncher(fixture,profile);
assert.throws(()=>requireLauncher(fixture,{machine:'pcjr',launcher:'PCJR/MISSING.BAT'}),/missing/);
assert.throws(()=>requireLauncher(new Uint8Array([1,2,3]),profile),/inspect/);
const config=windowsConfig(profile);
assert.ok(config.includes('machine=pcjr\n'));assert.ok(config.includes('memsizekb=640'));assert.ok(config.includes('cputype=8086_prefetch'));
assert.ok(!config.includes('WINXT.BAT'));
const guarded=bootstrap(config,'xt','guarded','XTD12345',profile.launcher);
const prompt=bootstrap(config,'xt','prompt','XTD12345',profile.launcher);
const decode=bytes=>new TextDecoder().decode(bytes);
assert.ok(decode(guarded.files[0].contents).includes('call C:\\PCJR\\STARTJR.BAT>>'));
assert.ok(!decode(prompt.files[0].contents).includes('call C:\\PCJR'));
assert.ok(decode(prompt.files[1].contents).includes('call C:\\PCJR\\STARTJR.BAT>>'));
const launch=await emulators.bundleUpdateConfig(fixture,{dosboxConf:guarded.config,jsdosConf:{version:'8'}});
assert.equal((await emulators.bundleConfig(launch)).dosboxConf,guarded.config);
requireLauncher(launch,profile);assert.equal(await sha256(fixture),before);
console.log('PASS 8 profile/launcher/archive safety checks; no DOS guest instantiated.');
